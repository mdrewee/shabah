export function getRandomFlyingQuestion(usedIds: string[] = []): FlyingQuestion {
  const available = FLYING_QUESTIONS.filter((q) => !usedIds.includes(q.id));
  const pool = available.length > 0 ? available : FLYING_QUESTIONS;
  const randomIndex = Math.floor(Math.random() * pool.length);
  return pool[randomIndex];
}

export function getQuestionsForMatch(count = 5): FlyingQuestion[] {
  const shuffled = [...FLYING_QUESTIONS].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count);
}
